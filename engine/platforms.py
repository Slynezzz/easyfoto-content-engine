def text_budget(pid: str | None) -> int:
    """Сколько знаков можно отдать тексту поста с картинкой или видео: лимит подписи площадки
    минус место под призыв со ссылкой, который движок добавляет сам."""
    p = get(pid) or PLATFORMS["tg"]
    return p["media_caption"] - p["cta_reserve"]


def get(pid: str | None) -> dict | None:
    return PLATFORMS.get(pid or "")


def label(pid: str | None) -> str:
    p = get(pid)
    return f"{p['emoji']} {p['title']}" if p else "все площадки"
